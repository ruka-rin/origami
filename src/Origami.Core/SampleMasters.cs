        """/....|../\\\.|.//.\\\./.../.\./.|////.\...\..|../.\..|..\./..\|""" +
        """\/....|.///\..|....\./....|..../.\...\./...\./""";

    /// <summary>PROTEIN：118 格 / 11 条竖折痕 -&gt; N=12 方形，折痕 91，成品 25×5 格。</summary>
    public const string Protein =
        """/.../.\././.\.../.../.\./.|////.\...\./...\./|\./|/..\.../.|...|""" +
        """.\.../..\...\..|../.\..|..\./..\|\/....|..../.\....|.\\\/..|..../""";
}
