namespace Origami.Core;

/// <summary>
/// 内置母版样例。
/// <para>
/// 这两个字符串是<b>题面原样</b>，放在库里而不是各程序各存一份：手抄母版是本项目
/// 最容易出错的地方 —— 反斜杠多一个少一个都还是<b>合法</b>母版，只是格数悄悄变了
/// （实测抄错一次会让 KRENIO 变成 99 格 / 82 折痕，肉眼完全看不出问题）。
/// 集中在此，GUI 与测试共用同一份，抄错的可能就消失了。</para>
/// <para>用 C# 11+ 的<b>原始字符串字面量</b> <c>"""..."""</c>：母版里有二十几个反斜杠，
/// <c>"\\"</c> 转义写法极易在反复编辑中数错个数；原始字符串里反斜杠就是反斜杠，
/// 一眼可数。两者都不含引号，因此不需要任何转义。按管道符切段只为控制行宽，
/// 拼接结果与原串逐字符相同。</para>
/// </summary>
public static class SampleMasters
{
    /// <summary>KRENIO：100 格 / 9 条竖折痕 -&gt; N=11 方形，折痕 80，成品 21×5 格。</summary>
